/** 設定画面やログイン画面から、文書を開くための合図 */
export const OPEN_LEGAL_EVENT = 'kimon-open-legal';

export function openLegal(key) {
  if (typeof window === 'undefined') return;
  window.dispatchEvent(new CustomEvent(OPEN_LEGAL_EVENT, { detail: key }));
}
